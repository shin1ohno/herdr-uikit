//! Window-local keyboard transitions. Only the application decides which
//! gestures request text input; UIKit reports visibility and minimization.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum Event {
    WillShow,
    DidShow,
    WillHide,
    DidHide,
}

/// The full software keyboard's lifecycle, separate from the layout guide:
/// a minimized keyboard can leave its assistant bar and text responder active.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub(super) enum Visibility {
    #[default]
    Hidden,
    Hiding,
    Showing,
    Visible,
}

impl Visibility {
    /// Returns false for a completion superseded by the opposite transition.
    pub(super) fn observe(&mut self, event: Event) -> bool {
        match event {
            Event::WillShow => *self = Self::Showing,
            Event::WillHide => *self = Self::Hiding,
            Event::DidShow if *self != Self::Hiding => *self = Self::Visible,
            Event::DidHide if !matches!(self, Self::Showing | Self::Visible) => {
                *self = Self::Hidden;
            }
            Event::DidShow | Event::DidHide => return false,
        }
        true
    }
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub(super) enum Dismissal {
    #[default]
    None,
    Application,
    User,
}

impl Dismissal {
    pub(super) fn allows_text(self) -> bool {
        self == Self::None
    }
}

/// Native resignations the window starts, including system lifecycle work.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum ResignReason {
    // keep-sorted start
    Application,
    FocusChange,
    Inactive,
    LeavingWindow,
    Restart,
    // keep-sorted end
}

/// Ownership and intent before UIKit can synchronously change either.
#[derive(Clone, Copy, Debug, Default)]
pub(super) struct ResignContext {
    pub(super) active: bool,
    pub(super) first_responder: bool,
    pub(super) reason: Option<ResignReason>,
    pub(super) text_requested: bool,
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub(super) struct Keyboard {
    pub(super) dismissal: Dismissal,
    /// Positive evidence that UIKit hid the keyboard while keeping our text
    /// responder. A keyboard never shown (including hardware-only input)
    /// must not cause explicit requests to restart the responder.
    pub(super) minimized: bool,
    /// Old hide notifications can arrive after a newer native acquisition.
    pending_hide: Option<ResignReason>,
    /// Only the current native resignation's intent, captured before UIKit.
    resign_reason: Option<ResignReason>,
    pub(super) visibility: Visibility,
}

impl Keyboard {
    pub(super) fn expect_hide(&mut self, reason: ResignReason) {
        self.pending_hide = Some(reason);
        self.resign_reason = Some(reason);
    }

    pub(super) fn resign_context(
        self,
        active: bool,
        first_responder: bool,
        text_requested: bool,
    ) -> ResignContext {
        ResignContext {
            active,
            first_responder,
            reason: self.resign_reason,
            text_requested,
        }
    }

    pub(super) fn resigned(&mut self, context: ResignContext) {
        self.minimized = false;
        // The hide key can resign before WillHide. An alert taking the native
        // responder also counts; neither may be undone by incidental GPUI focus.
        if context.active
            && context.first_responder
            && context.text_requested
            && context.reason.is_none()
            && self.resign_reason.is_none()
            && self.dismissal == Dismissal::None
        {
            self.dismissal = Dismissal::User;
        }
        if context.reason == self.resign_reason {
            self.resign_reason = None;
        }
    }

    pub(super) fn acquired(&mut self) {
        // A later unexpected resign belongs to the new acquisition. Its old
        // hide notification still needs separate suppression, including when
        // a hardware-only acquisition emits no keyboard show notification.
        self.resign_reason = None;
    }

    pub(super) fn focus_changed(&mut self) {
        // Preserve the app's existing focus-scoped hide. A user hide survives
        // FocusLost/FocusGained pairs generated by non-text gestures.
        if self.dismissal == Dismissal::Application {
            self.dismissal = Dismissal::None;
        }
    }

    pub(super) fn show(&mut self) {
        self.dismissal = Dismissal::None;
    }

    pub(super) fn hide(&mut self) {
        if self.dismissal != Dismissal::User {
            self.dismissal = Dismissal::Application;
        }
        self.expect_hide(ResignReason::Application);
    }
}

/// A notification's ownership, sampled before borrowing the window state.
#[derive(Clone, Copy, Debug, Default)]
pub(super) struct Context {
    pub(super) active: bool,
    pub(super) first_responder: bool,
    pub(super) key_window: bool,
    pub(super) local: bool,
    pub(super) screen_matches: Option<bool>,
    pub(super) text_requested: bool,
}

impl Context {
    pub(super) fn is_relevant(self) -> bool {
        self.local
            && self.active
            && self.key_window
            && (self.first_responder || self.text_requested)
            && self.screen_matches.unwrap_or(true)
    }
}

pub(super) fn on_keyboard_event(
    mut keyboard: Keyboard,
    event: Event,
    context: Context,
) -> Keyboard {
    // Unlike frame notifications, show/hide notifications identify a screen.
    // Missing or malformed screen identity cannot establish ownership.
    if context.screen_matches != Some(true)
        || !context.is_relevant()
        || !keyboard.visibility.observe(event)
    {
        return keyboard;
    }
    match event {
        Event::WillHide => {
            let intentional =
                keyboard.pending_hide.take().is_some() || keyboard.resign_reason.is_some();
            if !intentional {
                if context.first_responder {
                    keyboard.minimized = true;
                }
                if context.text_requested && keyboard.dismissal == Dismissal::None {
                    keyboard.dismissal = Dismissal::User;
                }
            }
        }
        Event::WillShow | Event::DidShow => {
            keyboard.minimized = false;
            keyboard.pending_hide = None;
            keyboard.acquired();
        }
        Event::DidHide => keyboard.pending_hide = None,
    }
    keyboard
}

