fn new_command_encoder_for_texture(
    command_buffer: &metal::CommandBufferRef,
    texture: &metal::TextureRef,
    viewport_size: Size<DevicePixels>,
    clear_color: Option<metal::MTLClearColor>,
) -> Result<metal::RenderCommandEncoder> {
    let render_pass_descriptor = metal::RenderPassDescriptor::new();
    let color_attachment = render_pass_descriptor
        .color_attachments()
        .object_at(0)
        .ok_or(Error::ColorAttachmentMissing)?;
    color_attachment.set_texture(Some(texture));
    color_attachment.set_store_action(metal::MTLStoreAction::Store);
    if let Some(clear_color) = clear_color {
        color_attachment.set_load_action(metal::MTLLoadAction::Clear);
        color_attachment.set_clear_color(clear_color);
    } else {
        color_attachment.set_load_action(metal::MTLLoadAction::Load);
    }

    let command_encoder =
        resources::render_command_encoder(command_buffer, render_pass_descriptor)?;
    command_encoder.set_viewport(metal::MTLViewport {
        originX: 0.0,
        originY: 0.0,
        width: i32::from(viewport_size.width) as f64,
        height: i32::from(viewport_size.height) as f64,
        znear: 0.0,
        zfar: 1.0,
    });
    Ok(command_encoder)
}

#[allow(unsafe_code)]
fn log_completion(completed: *mut objc2::runtime::AnyObject) {
    if completed.is_null() {
        tracing::warn!("Metal completion returned nil command buffer");
        return;
    }
    // SAFETY: Metal supplies a live command buffer for the callback's duration.
    // status returns NSUInteger; error returns a nullable, borrowed NSError.
    unsafe {
        let object = &*completed.cast::<objc2::runtime::AnyObject>();
        let status: u64 = objc2::msg_send![object, status];
        if status == metal::MTLCommandBufferStatus::Error as u64 {
            let error: Option<&objc2_foundation::NSError> = objc2::msg_send![object, error];
            tracing::warn!(status, error = ?error, "Metal command buffer failed");
        }
    }
}
